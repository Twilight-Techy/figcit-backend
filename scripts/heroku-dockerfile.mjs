// Writes Dockerfile.heroku from docker/api.Dockerfile, so Heroku builds the same image (heroku.yml).
// Heroku's builder has no BuildKit: the optional `ca` build secret and `COPY --chmod` are taken out.
// `node scripts/heroku-dockerfile.mjs` writes it; `--check` fails when it is out of date.
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../docker/api.Dockerfile', import.meta.url);
const target = new URL('../Dockerfile.heroku', import.meta.url);

export function forHeroku(dockerfile) {
  const body = dockerfile
    .replaceAll('--mount=type=secret,id=ca NODE_EXTRA_CA_CERTS=/run/secrets/ca ', '')
    .replace(
      /^COPY --chmod=(\d+) (\S+) (\S+)$/m,
      (_, mode, from, to) => `COPY ${from} ${to}\nRUN chmod ${mode} ${to}`,
    );
  if (body.includes('--mount=') || body.includes('--chmod='))
    throw new Error('docker/api.Dockerfile uses a BuildKit option this script does not handle');
  return `# Generated by scripts/heroku-dockerfile.mjs from docker/api.Dockerfile. Edit that file, not this one.\n${body}`;
}

const want = forHeroku(readFileSync(source, 'utf8'));
if (process.argv.includes('--check')) {
  let have = '';
  try {
    have = readFileSync(target, 'utf8');
  } catch {
    // Missing: out of date.
  }
  if (have !== want) {
    console.error('Dockerfile.heroku is out of date: run `pnpm heroku:dockerfile`.');
    process.exit(1);
  }
  console.log('Dockerfile.heroku is up to date.');
} else {
  writeFileSync(target, want);
  console.log('Wrote Dockerfile.heroku.');
}
