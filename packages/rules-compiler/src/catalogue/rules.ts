export function notSureRules(): readonly NotSureRule[] {
  const energies = ['empty', 'low', 'some', 'full'];
  const comforts = ['hard', 'uneasy', 'okay', 'good'];
  const rules: NotSureRule[] = [];
  // Specific body adjustments first.
  for (const [ei, energy] of energies.entries()) {
    for (const body of ['heavy', 'buzzy']) {
      rules.push({ when: [body, energy, 'okay'], cell: `E${String(ei + 1)}M2` });
    }
  }
  for (const [ei, energy] of energies.entries()) {
    for (const [ci, comfort] of comforts.entries()) {
      rules.push({ when: ['*', energy, comfort], cell: `E${String(ei + 1)}M${String(ci + 1)}` });
    }
  }
  return rules;
}

