const e = (
  code: string,
  label: string,
  emoji: string,
  family: string,
  side: 'harder' | 'lighter',
  riskAtIntensity?: number,
): SnapshotEmotion =>
  riskAtIntensity === undefined
    ? { code, label, emoji, family, side }
    : { code, label, emoji, family, side, riskAtIntensity };

