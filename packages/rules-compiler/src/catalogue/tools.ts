// Tool catalogue (workbook Tab 6d). Free tools in every pathway form the safety floor (ENT-1).
import type { Pathway, SnapshotTool } from '@figcit/engine';

interface ToolSpec {
  readonly id: string;
  readonly pathway: Pathway;
  readonly name: string;
  readonly tier?: 'free' | 'advanced';
  readonly floor?: boolean;
  readonly discreet?: boolean;
  readonly eyesOpen?: boolean;
  readonly audio?: boolean;
  readonly movement?: boolean;
  readonly verbal?: boolean;
  readonly leave?: boolean;
  readonly minutes: number;
  readonly practiceFormat?: SnapshotTool['practiceFormat'];
}

const t = (spec: ToolSpec): SnapshotTool => {
  const base: SnapshotTool = {
    id: spec.id,
    pathway: spec.pathway,
    name: spec.name,
    tier: spec.tier ?? 'free',
    safetyFloor: spec.floor ?? false,
    discreet: spec.discreet ?? false,
    eyesOpen: spec.eyesOpen ?? true,
    audio: spec.audio ?? false,
    movement: spec.movement ?? false,
    verbal: spec.verbal ?? false,
    leave: spec.leave ?? false,
    minutes: spec.minutes,
  };
  return spec.practiceFormat ? { ...base, practiceFormat: spec.practiceFormat } : base;
};

